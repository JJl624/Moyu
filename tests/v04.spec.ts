    await expect(blocks.nth(3).locator('.code-output')).toHaveText('8\n');
    await page.getByRole('button',{name:'源码',exact:true}).click();
    await expect(page.locator('.code-result,.code-ui')).toHaveCount(0);
    await page.getByRole('button',{name:'阅读',exact:true}).click();
    await expect(page.locator('.reading-view .tok-keyword').first()).toBeVisible();
    await expect(page.locator('.reading-view .code-block-shell').nth(3).locator('.code-output')).toHaveText('8\n');
    await page.locator('.reading-view .code-block-shell').first().locator('pre > code').click({button:'right'});
    await expect(page.getByRole('menuitem',{name:'复制代码',exact:true})).toBeVisible();
    await expect(page.getByRole('menuitem',{name:'设为一级标题',exact:true})).toHaveCount(0);
